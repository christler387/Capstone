// Writes src/vendor/boxicons.css: the Boxicons stylesheet with only the icons the app uses,
// and font-display: swap so text stays visible while the icon font loads.
// Run it again after adding a new icon name: npm run icons
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'node_modules/boxicons/css/boxicons.css'), 'utf8');

// Every icon name written anywhere in the app's source.
const used = new Set();
const scan = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(full);
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) {
      for (const match of fs.readFileSync(full, 'utf8').matchAll(/\bbxs?-?l?-[a-z0-9-]+|\bbx(?:s|l)?-[a-z0-9-]*/g)) {
        used.add(match[0]);
      }
    }
  }
};
scan(path.join(root, 'src'));
const usedPrefixes = [...used].filter((name) => name.endsWith('-'));
const isUsed = (cls) => used.has(cls) || usedPrefixes.some((prefix) => cls.startsWith(prefix));

// Walk the top-level blocks of the stylesheet, keeping braces balanced.
const blocks = [];
let i = 0;
while (i < source.length) {
  const open = source.indexOf('{', i);
  if (open === -1) break;
  let depth = 1;
  let j = open + 1;
  while (j < source.length && depth > 0) {
    if (source[j] === '{') depth += 1;
    else if (source[j] === '}') depth -= 1;
    j += 1;
  }
  blocks.push({ prelude: source.slice(i, open).trim(), body: source.slice(open + 1, j - 1) });
  i = j;
}

const kept = [];
for (const { prelude, body } of blocks) {
  if (prelude.startsWith('@font-face')) {
    // Only the woff2 and woff files are used; the older formats are dropped.
    // The font has several src lines (one per format); they are replaced by a single woff2/woff list.
    let placed = false;
    const rewritten = body
      .replace(/src:[^;]*;/g, () => {
        if (placed) return '';
        placed = true;
        return "src: url('../../node_modules/boxicons/fonts/boxicons.woff2') format('woff2'), url('../../node_modules/boxicons/fonts/boxicons.woff') format('woff');";
      })
      .replace(/font-display:[^;]*;/, '');
    kept.push(`@font-face {\n    ${rewritten.trim().replace(/\n\s*/g, '\n    ')}\n    font-display: swap;\n}`);
    continue;
  }
  if (prelude.startsWith('@')) {
    // Animations and other at-rules are small; keep them whole.
    kept.push(`${prelude} {${body}}`);
    continue;
  }
  const classes = [...prelude.matchAll(/\.(bxs?-?l?-?[a-z0-9-]+)/g)].map((m) => m[1]);
  const iconClasses = classes.filter((cls) => /^bx[sl]?-/.test(cls) && cls !== 'bx');
  if (iconClasses.length > 0 && !iconClasses.some(isUsed)) continue;
  kept.push(`${prelude} {${body}}`);
}

const header = '/* Generated by scripts/build-icons.mjs from boxicons 2.1.4. Edit the script, not this file. */\n';
const outDir = path.join(root, 'src/vendor');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'boxicons.css'), header + kept.join('\n\n') + '\n');
console.log(`boxicons: ${used.size} icon names found, ${kept.length} rules kept`);
